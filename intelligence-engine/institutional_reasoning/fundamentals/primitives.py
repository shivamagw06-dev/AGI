FISCAL_YEARS = ("FY17", "FY18", "FY19", "FY20", "FY21", "FY22", "FY23", "FY24", "FY25", "FY26")

# entity -> field -> {fy: value}
_PANEL: dict[str, dict[str, dict[str, float]]] = {}


def _register(entity_id: str, rows: dict[str, tuple[float, ...]]) -> None:
    panel: dict[str, dict[str, float]] = {}
    for field, values in rows.items():
        if len(values) != len(FISCAL_YEARS):
            raise ValueError(f"{entity_id}.{field}: expected {len(FISCAL_YEARS)} points")
        panel[field] = {fy: float(v) for fy, v in zip(FISCAL_YEARS, values)}
    _PANEL[entity_id.upper()] = panel


