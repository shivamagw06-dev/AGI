def has_primitives(entity_id: str | None) -> bool:
    return str(entity_id or "").upper() in _PANEL


def covered_entities() -> list[str]:
    return sorted(_PANEL)


def primitive_series(entity_id: str, field: str) -> dict[str, float] | None:
    panel = _PANEL.get(str(entity_id or "").upper())
    if not panel:
        return None
    series = panel.get(field)
    return dict(series) if series else None


def primitive_panel(entity_id: str) -> dict[str, dict[str, float]] | None:
    panel = _PANEL.get(str(entity_id or "").upper())
    return {k: dict(v) for k, v in panel.items()} if panel else None


def latest(entity_id: str, field: str) -> float | None:
    series = primitive_series(entity_id, field)
    if not series:
        return None
    for fy in reversed(FISCAL_YEARS):
        if fy in series:
            return series[fy]
    return None


