def list_entities() -> list[str]:
    return sorted(CORPUS.keys())


def get_corpus(key: Optional[str] = None) -> Optional[dict[str, Any]]:
    if not key:
        return None
    k = str(key).strip().lower().replace(" ", "_")
    k = ENTITY_ALIASES.get(k, ENTITY_ALIASES.get(k.replace("_", " "), k))
    c = CORPUS.get(k)
    return dict(c) if c else None


def resolve_entity(text: Optional[str]) -> Optional[str]:
    if not text:
        return None
    low = " ".join(str(text).lower().split())
    for alias, key in sorted(ENTITY_ALIASES.items(), key=lambda kv: -len(kv[0])):
        if alias in low:
            return key
    for key in CORPUS:
        if key.replace("_", " ") in low:
            return key
    return None
