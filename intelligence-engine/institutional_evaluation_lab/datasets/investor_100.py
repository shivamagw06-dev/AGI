def _build(spec: tuple[str, str, str, str, str | None, str]) -> dict:
    question_id, text, category, sector, ticker_hint, answer_format = spec
    intent, evidence, frameworks, playbooks = _PROFILE[answer_format]
    return question(
        question_id,
        text=text,
        category=category,
        intent=intent,
        frameworks=frameworks,
        expected_evidence=evidence,
        expected_playbook=playbooks,
        expected_reasoning=[answer_format.replace("_", " ")],
        difficulty="medium",
        sector=sector,
        ticker_hint=ticker_hint,
        answer_format=answer_format,
        suite="investor_100",
        version="investor-100-v1",
        tags=["investor_100", sector, answer_format],
    )


INVESTOR_100 = [_build(spec) for spec in _SPECS]
