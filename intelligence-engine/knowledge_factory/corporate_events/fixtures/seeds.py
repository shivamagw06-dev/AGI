    return {
        "type": type,
        "announcement_date": announcement_date,
        "effective_date": effective_date or announcement_date,
        "available_from": available_from or announcement_date,
        "title": title,
        "source": source,
        "importance": importance,
        "confidence": confidence,
        "evidence": [evidence] if isinstance(evidence, str) else list(evidence),
        "impact": impact or {},
        "affected_companies": list(affected_companies or []),
        "affected_sectors": list(affected_sectors or []),
        "affected_macro": list(affected_macro or []),
    }


