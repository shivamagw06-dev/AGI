def _p(
    *,
    policy_id: str,
    name: str,
    domain: str,
    policy_type: str,
    government_body: str,
    announcement_date: str,
    effective_date: str,
    available_from: str | None = None,
    expiry: str | None = None,
    jurisdiction: str = "India",
    source: str,
    evidence: str | list[str],
    confidence: float = 0.9,
    affected_sectors: list[str] | None = None,
    affected_industries: list[str] | None = None,
    affected_companies: list[str] | None = None,
    affected_commodities: list[str] | None = None,
    impact_level: str = "High",
    transmission: dict[str, Any] | None = None,
    historical_versions: list[str] | None = None,
    notes: str | None = None,
    instruments: dict[str, Any] | None = None,
) -> dict[str, Any]:
    return {
        "policy_id": policy_id,
        "name": name,
        "domain": domain,
        "policy_type": policy_type,
        "government_body": government_body,
        "announcement_date": announcement_date,
        "effective_date": effective_date,
        "available_from": available_from or announcement_date,
        "expiry": expiry,
        "jurisdiction": jurisdiction,
        "source": source,
        "evidence": [evidence] if isinstance(evidence, str) else list(evidence),
        "confidence": confidence,
        "affected_sectors": list(affected_sectors or []),
        "affected_industries": list(affected_industries or []),
        "affected_companies": list(affected_companies or []),
        "affected_commodities": list(affected_commodities or []),
        "impact_level": impact_level,
        "transmission": transmission or {},
        "historical_versions": list(historical_versions or []),
        "instruments": instruments or {},
        "notes": notes,
    }


